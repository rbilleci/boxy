CREATE OR REPLACE FUNCTION fn_random_int()
    RETURNS INT
    LANGUAGE plpgsql
    NOT DETERMINISTIC
AS $$
BEGIN
  -- RANDOM() ∈ [0,1)
  -- *2^32 → [0 … 4294967296)
  -- FLOOR() → {0 … 4294967295}
  -- -2^31 → {–2147483648 … +2147483647}
  RETURN CAST(FLOOR(RANDOM() * 4294967296) - 2147483648 AS INT);
END;
$$;
