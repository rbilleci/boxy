CREATE FUNCTION fn_random_int()
    RETURNS INT
    NO SQL
    NOT DETERMINISTIC
    SQL SECURITY INVOKER
BEGIN
  -- RAND() ∈ [0,1)
  -- *2^32 → [0 … 4294967296)
  -- FLOOR() → {0 … 4294967295}
  -- -2^31 → {–2147483648 … +2147483647}
  RETURN CAST(FLOOR(RAND() * 4294967296) - 2147483648 AS SIGNED);
END;